    existing = set(db.recent_topic_keys(500))
    output_dir = Path("output/manual_posts")
    output_dir.mkdir(parents=True, exist_ok=True)
    for post in POSTS:
        slug = re.sub(r"[^a-z0-9-]", "", post["topic_key"])
        (output_dir / f"{slug}.html").write_text(post["content_html"], encoding="utf-8")
        metadata = {key: value for key, value in post.items() if key != "content_html"}
        (output_dir / f"{slug}.json").write_text(
            json.dumps(metadata, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        if post["topic_key"] in existing:
            print(f"skip: {post['title']}")
            continue
        post_id = db.save_post(post)
        print(f"created {post_id}: {post['title']}")


